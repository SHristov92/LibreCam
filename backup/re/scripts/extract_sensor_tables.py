"""Extract the stock firmware's camera sensor {reg, value} init tables into a C header.

Usage: python3 -I extract_sensor_tables.py app_0x10000.bin out.h
Addresses and pair counts come from the init dispatcher (0x9bbb0), the PPI setter (0x9c238),
day/night (0x9b22c) and the GC2145/OV7740 routines (0x9ca54, 0x9cae8, 0x9cc90).
"""
import sys

BASE = 0x10000
# name, address, pairs, note
TABLES = [
    ('gc2145_init',       0x16fc06, 637, 'addr 0x3C, after detect (0x9ca54)'),
    ('gc2145_mode1',      0x170215,  23, 'applied by 0x9cae8(1) right after init'),
    ('gc2145_mode2',      0x1701db,  23, '0x9cae8(2)'),
    ('ov7740_init',       0x170967, 122, 'addr 0x21 (0x9cc90)'),
    ('sp0a39_init',       0x16e52a, 352, "addr 0x21, type 'L'"),
    ('sp0a20_init',       0x16ed1e, 399, "addr 0x21, type 'S'"),
    ('sp0a28_init',       0x16ea48, 280, "addr 0x3D, type 'b'"),
    ('sp0828_init',       0x16f836, 268, "addr 0x18, type 'T'"),
    ('sp0a19_init',       0x16da26, 289, "addr 0x21, type 'Y'"),
    ('bf20a6_init',       0x16e1ac, 133, "addr 0x6E, type 'R'"),
    ('gc0307_init',       0x16d466, 315, "addr 0x21, type 'Q'"),
    ('gc0308_init',       0x16e7fe, 284, "addr 0x21, type '_'"),
    ('gc0310_gc0312_init',0x16e2b6, 314, "addr 0x21, type 'd'"),
    ('gc0311_init',       0x16d258, 263, "addr 0x33, type 'a'"),
    ('gc0311_qvga',       0x16ecf2,  12, 'PPI 0 (0x9c238)'),
    ('gc0311_vga',        0x16ec78,   7, 'PPI 1 (0x9c238)'),
    ('gc0328c_init',      0x16de6e, 375, "addr 0x21, type ']'"),
    ('gc0328c_qvga',      0x16d9d0,  12, 'PPI 0 (0x9c238)'),
    ('gc0328c_vga',       0x16ecda,  12, 'PPI 1 (0x9c238)'),
    ('gc0309_init',       0x16d6dc, 218, "addr 0x21, type '`'"),
    ('gc0329c_init',      0x16dc68, 259, "addr 0x31, type 'c'"),
    ('gc0329c_day',       0x16ec86,  21, 'day/night 0 (0x9b22c)'),
    ('gc0329c_night',     0x16ecb0,  21, 'day/night 1 (0x9b22c)'),
    ('siv121_init',       0x16d890, 160, "addr 0x33, type 'N' (not probed)"),
]

img = open(sys.argv[1], 'rb').read()
out = ['/* Generated by backup/re/scripts/extract_sensor_tables.py from stock firmware',
       ' * 3.00.21.01_251205. {reg, value} pairs, written in order over SCCB. Do not edit. */',
       '#ifndef A9_STOCK_SENSOR_TABLES_H', '#define A9_STOCK_SENSOR_TABLES_H', '', '#include <stdint.h>', '']
for name, addr, pairs, note in TABLES:
    raw = img[addr - BASE: addr - BASE + pairs * 2]
    out.append(f'/* {note}; stock address 0x{addr:x} */')
    out.append(f'static const uint8_t {name}[{pairs}][2] = {{')
    for i in range(0, len(raw), 16):
        out.append('    ' + ' '.join(f'{{0x{raw[j]:02x}, 0x{raw[j+1]:02x}}},' for j in range(i, min(i + 16, len(raw)), 2)))
    out.append('};\n')
out.append('#endif')
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
print(f'{len(TABLES)} tables, {sum(t[2] for t in TABLES)} pairs')
