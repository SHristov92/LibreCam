"""Extract the rear view camera's stock sensor init tables into a C header.

Usage: python3 -I extract_sensor_tables.py app_0x10000.bin out.h
Addresses come from the init dispatcher (0x45244) and the PPI setter (0x465dc). Each
dispatcher loop walks base+1 .. base+N in steps of 2, so a table at base holds (N - 1) / 2
{reg, value} pairs. HM1055's table has 16-bit registers: {u16 reg (LE), u8 value, pad}.
"""
import struct
import sys

BASE = 0x10000
# name, address, pairs, note
TABLES = [
    ('gc0308_rv_init',  0xfda84, 297, 'GC0308, addr 0x21, ID 00=9B'),
    ('gc0309_rv_init',  0xfe4d8, 224, 'GC0309, addr 0x21, ID 00=A0'),
    ('gc0311_rv_init',  0xfeb80, 264, 'GC0311, addr 0x33, ID F0=BB (fitted on our unit)'),
    ('gc0312_rv_init',  0xfedda, 287, 'GC0312, addr 0x21, ID F0=B3'),
    ('gc0328c_rv_init', 0xffdf2, 371, 'GC0328C, addr 0x21, ID F0=9D'),
    ('gc0328c_rv_qvga', 0xffdda,  12, 'GC0328C PPI 0 (0x465dc)'),
    ('gc0329_init',     0xfcebe, 256, 'GC0329, addr 0x31, FC=16 then ID 00=C0'),
    ('hi704_init',      0x100294, 383, 'HI704, addr 0x3C, ID 04=96'),
    ('ov7670_init',     0xfe066, 170, 'OV7670, addr 0x21, ID 0A=76'),
    ('ov7673_init',     0xfd12e, 148, 'OV7673, addr 0x33, ID 01=0C'),
    ('sp0a19_rv_init',  0xfde10, 271, 'SP0A19, addr 0x21, ID 02=A6; also used for SP0A38 (ID 01=0A)'),
    ('sp2518_init',     0xfd278, 361, 'SP2518, addr 0x30, ID 02=53'),
    ('sc030_init',      0xff3e8, 188, 'SC030, addr 0x68, ID F8=46'),
    ('pas6329_page0',   0x100142, 169, 'PAS6329, addr 0x40, ID 00=63: after EF=00'),
    ('pas6329_page1',   0xfe1dc, 146, 'PAS6329: after EF=01'),
    ('pas6329_page2',   0xfe300, 138, 'PAS6329: after EF=02, then EF=00'),
    ('pas6375_init',    0xfe6aa, 619, 'PAS6375, addr 0x40, ID 00=63 (same ID: stock writes both PAS tables)'),
    ('bf2013_init',     0x1005c0, 135, 'BF2013, addr 0x6E, ID 00=63'),
    ('bf3a03_init',     0x100716, 126, 'BF3A03, addr 0x6E, ID FC=3A'),
    ('bf20a6_rv_init',  0xfdd06, 133, 'BF20A6, addr 0x6E, ID FC=20'),
]
# GC0311's PPI change is code, not a table (0x465dc): FE=00, then 59=22 (QVGA) or 59=11 (VGA).
LITERALS = [
    ('gc0311_rv_qvga', [(0xfe, 0x00), (0x59, 0x22)], 'GC0311 PPI 0 (0x465dc)'),
]
HM1055 = ('hm1055_init', 0xff56a, 540, 'HM1055, addr 0x24, 16-bit ID 0001=09')


def pairs_c(name, raw_pairs, note):
    out = [f'/* {note} */', f'static const uint8_t {name}[{len(raw_pairs)}][2] = {{']
    for i in range(0, len(raw_pairs), 8):
        out.append('    ' + ' '.join(f'{{0x{r:02x}, 0x{v:02x}}},' for r, v in raw_pairs[i:i + 8]))
    return out + ['};', '']


img = open(sys.argv[1], 'rb').read()
out = ['/* Generated by backup/re-rearview/scripts/extract_sensor_tables.py from the rear view',
       ' * camera\'s stock firmware CYCam-A9 3.2. {reg, value} pairs, written in order over SCCB.',
       ' * Do not edit. */',
       '#ifndef LC_STOCK_SENSOR_TABLES_REARVIEW_H', '#define LC_STOCK_SENSOR_TABLES_REARVIEW_H', '',
       '#include <stdint.h>', '']
for name, addr, n, note in TABLES:
    raw = img[addr - BASE: addr - BASE + n * 2]
    out += pairs_c(name, [(raw[i], raw[i + 1]) for i in range(0, len(raw), 2)],
                   f'{note}; stock address 0x{addr:x}')
for name, pairs, note in LITERALS:
    out += pairs_c(name, pairs, note)

name, addr, n, note = HM1055
out += [f'/* {note}; stock address 0x{addr:x} */',
        f'static const struct {{ uint16_t reg; uint8_t val; }} {name}[{n}] = {{']
ent = [struct.unpack_from('<HB', img, addr - BASE + 4 * k) for k in range(n)]
for i in range(0, n, 6):
    out.append('    ' + ' '.join(f'{{0x{r:04x}, 0x{v:02x}}},' for r, v in ent[i:i + 6]))
out += ['};', '', '#endif']
open(sys.argv[2], 'w').write('\n'.join(out) + '\n')
